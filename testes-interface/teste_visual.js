const { chromium } = require("playwright");
const fs = require("fs");
(async () => {
  const browser = await chromium.launch();
  const fake = fs.readFileSync(__dirname + "/fake_webgazer.js", "utf8");
  const ok = (c, m) => { if (!c) { console.log("FALHOU: " + m); process.exitCode = 1; } else console.log("  ok - " + m); };
  const erros = [];
  async function abrir(w, h) {
    const page = await browser.newPage({ viewport: { width: w, height: h } });
    page.on("pageerror", (e) => erros.push(e.message));
    await page.route("**/webgazer.js", (r) => r.fulfill({ body: fake, contentType: "text/javascript" }));
    await page.goto("http://127.0.0.1:5500/index.html"); await page.waitForTimeout(400);
    await page.screenshot({ path: `splash-${w}.png` });
    await page.waitForTimeout(1200);
    await page.screenshot({ path: `login-${w}.png` });
    await page.fill("#login-email", "a@x.com"); await page.fill("#login-senha", "x"); await page.click("#login-enviar");
    await page.waitForTimeout(800);
    if (await page.isVisible("#boas-vindas")) await page.click("#btn-comecar");
    return page;
  }
  const page = await abrir(1280, 820);
  ok(await page.evaluate(() => document.documentElement.dataset.tema) === "revoz", "tema Revoz por padrão");
  ok(await page.title() === "Revoz", "título Revoz");
  ok((await page.textContent("#info-papel")) === "Conta de usuário", "papel aparece como usuário");
  await page.click("#aba-conta"); await page.waitForTimeout(400); ok(await page.isVisible("#btn-auditoria") && await page.isVisible("#vinc-ajuda"), "aba Conta tem privacidade e vínculos"); await page.screenshot({ path: "rv-conta.png" });
  await page.click("#logo-inicio"); ok(await page.isVisible("#painel-digitar"), "logo volta para o Digitar");
  await page.screenshot({ path: "rv-digitar.png" });
  await page.click("#aba-vozes"); await page.waitForTimeout(500); await page.screenshot({ path: "rv-vozes.png" });
  await page.click("#aba-ajustes"); await page.waitForTimeout(300);
  ok(await page.isChecked("#ajuste-emergencia"), "emergência vem ligada");
  await page.click("label:has(#ajuste-emergencia)");
  ok(await page.isHidden("#btn-emergencia"), "desligar esconde o botão do topo");
  await page.screenshot({ path: "rv-ajustes.png" });
  await page.click("#aba-olhar"); await page.waitForTimeout(1500);
  await page.waitForSelector("#calibracao", { state: "hidden", timeout: 60000 });
  const tiles = await page.$$eval("#grade .frase", (t) => t.map((x) => x.textContent));
  ok(!tiles.includes("Emergência"), "sem emergência na grade do Olhar: " + tiles);
  await page.screenshot({ path: "rv-olhar.png" });
  await page.click("#aba-ajustes"); await page.click("label:has(#ajuste-emergencia)");
  ok(await page.isVisible("#btn-emergencia"), "religar mostra de novo");
  await page.check("input[name='ajuste-tema'][value='classico']");
  ok(await page.evaluate(() => document.documentElement.dataset.tema) === "classico", "troca para o clássico na hora");
  await page.reload(); await page.waitForTimeout(1500);
  ok(await page.evaluate(() => document.documentElement.dataset.tema) === "classico", "tema fica salvo");
  await page.evaluate(() => localStorage.setItem("ajuste:tema", '"revoz"'));
  const cel = await abrir(390, 800);
  await cel.screenshot({ path: "rv-celular.png" }); await cel.click("#aba-conta"); await cel.waitForTimeout(400); await cel.screenshot({ path: "rv-celular-conta.png" });
  await cel.click("#aba-olhar"); await cel.waitForTimeout(800);
  ok(!erros.length, "sem erros " + erros.join("|"));
  await browser.close();
})();
