const { chromium } = require("playwright");
const fs = require("fs");
const API = "http://127.0.0.1:8080";
(async () => {
  const browser = await chromium.launch();
  const fake = fs.readFileSync(__dirname + "/fake_webgazer.js", "utf8");
  const ok = (c, m) => { if (!c) { console.log("FALHOU: " + m); process.exitCode = 1; } else console.log("  ok - " + m); };
  const erros = [];
  const page = await browser.newPage({ viewport: { width: 1280, height: 820 } });
  page.on("pageerror", (e) => erros.push(e.message));
  await page.route("**/webgazer.js", (r) => r.fulfill({ body: fake, contentType: "text/javascript" }));
  await page.route("**/fonts.googleapis.com/**", (r) => r.abort());
  await page.goto("http://127.0.0.1:5500/index.html"); await page.waitForTimeout(1300);
  ok(await page.isHidden("#login-grupo-nome"), "no Entrar não pede nome");
  // conta antiga, sem nome
  await page.fill("#login-email", "ana@x.com"); await page.fill("#login-senha", "x"); await page.click("#login-enviar");
  await page.waitForTimeout(700);
  ok((await page.textContent("#bv-titulo")) === "Bem-vindo ao Revoz", "boas-vindas sem nome");
  if (await page.isVisible("#boas-vindas")) await page.click("#btn-comecar");
  ok(await page.textContent("#btn-perfil .avatar") === "AN" && await page.textContent("#btn-perfil .perfil-nome") === "ana", "sem nome: iniciais e nome do e-mail no topo");
  await page.click("#btn-perfil");
  ok(await page.isVisible("#painel-conta"), "tocar no nome do topo abre a Conta");
  ok((await page.textContent("#nome-msg")).startsWith("Adicione"), "pede para adicionar o nome");
  ok((await page.textContent("#btn-editar-nome")) === "Adicionar nome", "botão Adicionar nome");
  await page.screenshot({ path: "nome-vazio.png" });
  await page.click("#btn-editar-nome");
  await page.fill("#campo-nome", "x");
  await page.click("#form-nome button[type=submit]");
  ok((await page.textContent("#nome-msg")) === "Escreva o seu nome.", "nome curto recusado");
  await page.fill("#campo-nome", "  Erick   Domingos ");
  await page.click("#form-nome button[type=submit]"); await page.waitForTimeout(400);
  ok((await (await fetch(API + "/_estado")).json()).nome === "Erick Domingos", "salvou no servidor");
  ok(await page.textContent("#btn-perfil .avatar") === "ED" && await page.textContent("#btn-perfil .perfil-nome") === "Erick", "topo: ED e Erick");
  ok(await page.textContent("#conta-avatar") === "ED" && await page.textContent("#info-nome") === "Erick Domingos", "Conta mostra o nome");
  ok(await page.isHidden("#form-nome") && (await page.textContent("#nome-msg")) === "Nome salvo.", "fecha o formulário");
  await page.screenshot({ path: "nome-conta.png" });
  await page.click("#aba-digitar"); await page.screenshot({ path: "nome-topo.png" });
  // sair e criar conta nova com nome
  await page.click("#btn-sair-topo"); await page.waitForTimeout(300);
  ok(await page.isHidden("#btn-perfil"), "ao sair, o nome some do topo");
  await page.click("#login-alternar");
  ok(await page.isVisible("#login-nome"), "Criar conta pede o nome");
  await page.fill("#login-email", "ana@x.com"); await page.fill("#login-senha", "12345678");
  await page.click("#login-enviar");
  ok((await page.textContent("#login-erro")) === "Escreva o seu nome.", "criar conta sem nome: recusa");
  await page.fill("#login-nome", "Leonardo"); await page.click("#login-enviar"); await page.waitForTimeout(700);
  ok(await page.textContent("#btn-perfil .avatar") === "L", "uma palavra: só a inicial");
  await page.evaluate(() => localStorage.removeItem("onboarding"));
  await page.reload(); await page.waitForTimeout(1500);
  ok((await page.textContent("#bv-titulo")) === "Bem-vindo ao Revoz, Leonardo", "boas-vindas com o nome");
  const cel = await browser.newPage({ viewport: { width: 375, height: 740 } });
  await cel.route("**/webgazer.js", (r) => r.fulfill({ body: fake, contentType: "text/javascript" }));
  await cel.route("**/fonts.googleapis.com/**", (r) => r.abort());
  await cel.goto("http://127.0.0.1:5500/index.html"); await cel.waitForTimeout(1300);
  await cel.fill("#login-email", "ana@x.com"); await cel.fill("#login-senha", "x"); await cel.click("#login-enviar"); await cel.waitForTimeout(700);
  if (await cel.isVisible("#boas-vindas")) await cel.click("#btn-comecar");
  const larg = await cel.evaluate(() => [document.documentElement.scrollWidth, innerWidth]);
  ok(larg[0] <= larg[1], "celular sem rolagem horizontal " + larg);
  const topo = await cel.$eval(".topo", (e) => e.getBoundingClientRect().height);
  ok(topo < 80, "topo do celular em uma linha (" + Math.round(topo) + " px)");
  await cel.screenshot({ path: "nome-celular.png" });
  await cel.click("#aba-conta"); await cel.screenshot({ path: "nome-celular-conta.png" });
  ok(!erros.length, "sem erros " + erros.join("|"));
  await browser.close();
})();
